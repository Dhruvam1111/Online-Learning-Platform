-- UTC timestamps are stored as TIMESTAMP WITHOUT TIME ZONE (UTC by application convention).
CREATE TABLE IF NOT EXISTS student_study_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES users(id),
    course_id INTEGER NOT NULL REFERENCES courses(id),
    title VARCHAR(200) NOT NULL,
    notes TEXT,
    starts_at_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ends_at_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    CONSTRAINT ck_student_study_sessions_order CHECK (ends_at_utc > starts_at_utc)
);
CREATE INDEX IF NOT EXISTS idx_student_study_sessions_student_start
    ON student_study_sessions (student_id, starts_at_utc);
